function normalize(str) {
  return str
    ?.toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim() || "";
}

function getFeatureId(feature) {
  const p = feature.properties || {};
  const reg = game.region;

  let id;

  // --- CASO 1: TUCUMÁN ---
  if (reg === "ar-tucuman") {
    id = p.id;
  } 
  // --- CASO 2: BRITISH COLUMBIA (Canadá) ---
  else if (reg === "ca-bc") {
    let raw = p.CDNAME || p.RD_NAME || p.ADMIN_AREA_NAME || p.name || "Desconocido";
    id = normalize(raw);

    const aliases = {
      "greater vancouver": "metro vancouver",
      "powell river": "qathet"
    };

    if (aliases[id]) {
      return aliases[id];
    }
    return id;
  }
  // --- CASO 3: GENÉRICO (Países, Continentes y Santa Catarina) ---
  else {
    // Busca en propiedades comunes de GeoJSON
    let name = p.NM_MUN || p.NM_MUNICIP || p.nome_rgi || p.name || p.nombre || p.NAM || p.nam || p.nom || p.departamento || p.provincia || p.admin || "Desconocido";
    return normalize(name);
  }

  return id ? id.toString() : null;
}

function getFeatureName(feature) {
  const p = feature.properties || {};
  
  if (game.region === "ca-bc") {
      return p.CDNAME || p.RD_NAME || p.name || "Desconocido";
  }
  
  return (
    p.NM_MUN ||
    p.nome_rgi ||
    p.departamento ||
    p.nombre ||
    p.name ||
    p.NAM ||
    p.admin || // Agregado para continentes (Admin-0 countries)
    "Desconocido"
  );
}

function getRegionKey(region) {
  const aliases = {
    "br-sc": "br-santacatarina",
    "br-santa-catarina": "br-santacatarina"
  };
  return aliases[region] || region;
}

